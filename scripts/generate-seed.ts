/**
 * Generates supabase/seed.sql: fitment reference data, category tree, 12 real products
 * picked from the eBay export (one per category group where possible) with parsed
 * fitment, and 3 clearly-labelled DEMO donor vehicles.
 *
 *   npm run db:seed:generate -- data/imports/<file>.csv
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import Papa from "papaparse";
import { CATEGORY_GROUPS, FALLBACK_CATEGORY_GROUP } from "../src/lib/import/category-groups";
import { activeListingRowSchema, mapActiveListingRow, slugify, type ProductImport } from "../src/lib/import/ebay-mapping";
import { VEHICLE_REFERENCE } from "../src/lib/import/vehicle-reference";

const file = process.argv[2];
if (!file) {
  console.error("Usage: npm run db:seed:generate -- <file.csv>");
  process.exit(1);
}

const q = (v: string | null | undefined) => (v === null || v === undefined ? "null" : `'${v.replace(/'/g, "''")}'`);
const arr = (values: string[]) => (values.length ? `array[${values.map(q).join(", ")}]::text[]` : "'{}'::text[]");

const text = readFileSync(resolve(file), "utf8").replace(/^﻿/, "");
const rows = Papa.parse<Record<string, string>>(text, { header: true, skipEmptyLines: true }).data;
const products: ProductImport[] = rows.flatMap((raw) => {
  const parsed = activeListingRowSchema.safeParse(raw);
  return parsed.success ? [mapActiveListingRow(parsed.data)] : [];
});

// Demo donor vehicles: model slugs chosen so seed parts can be linked to them.
const DEMO_VEHICLES = [
  { stock: "DEMO-101", year: 2018, make: "kia", model: "stinger", trim: "GT", odometer: 64210, engine: "3.3L V6 Twin Turbo", transmission: "8-speed automatic", drive: "RWD", color: "HiChroma Red" },
  { stock: "DEMO-102", year: 2019, make: "chevrolet", model: "malibu", trim: "LT", odometer: 48112, engine: "1.5L I4 Turbo", transmission: "CVT", drive: "FWD", color: "Summit White" },
  { stock: "DEMO-103", year: 2015, make: "bmw", model: "3-series", trim: "328i", odometer: 91877, engine: "2.0L I4 Turbo", transmission: "8-speed automatic", drive: "RWD", color: "Jet Black" },
];

// Pick: one well-parsed product per group, preferring the demo vehicles' models, until 12.
const wellParsed = products.filter((p) => p.fitment.makeSlug && p.fitment.modelSlug && p.oemPartNumber && p.fitment.years.length);
const picked: ProductImport[] = [];
for (const vehicle of DEMO_VEHICLES) {
  const matches = wellParsed.filter((p) => p.fitment.modelSlug === vehicle.model && p.fitment.years.includes(vehicle.year));
  const groups = new Set<string>();
  for (const p of matches) {
    if (picked.length >= 6 || groups.size >= 2) break;
    if (!groups.has(p.category.groupSlug)) {
      groups.add(p.category.groupSlug);
      picked.push(p);
    }
  }
}
for (const group of CATEGORY_GROUPS) {
  if (picked.length >= 12) break;
  if (picked.some((p) => p.category.groupSlug === group.slug)) continue;
  const p = wellParsed.find((x) => x.category.groupSlug === group.slug && !picked.includes(x));
  if (p) picked.push(p);
}

const lines: string[] = [];
lines.push("-- Generated by scripts/generate-seed.ts. Do not edit by hand.");
lines.push(`-- Source: ${file.replace(/\\/g, "/").split("/").pop()} (${products.length} rows parsed, ${picked.length} seeded)`);
lines.push("begin;", "");

lines.push("-- Makes & models (fitment reference)");
VEHICLE_REFERENCE.forEach((make, i) => {
  lines.push(
    `insert into public.makes (name, slug, aliases, is_featured, sort_order) values (${q(make.name)}, ${q(make.slug)}, ${arr(make.aliases)}, ${Boolean(make.featured)}, ${i}) on conflict (slug) do update set aliases = excluded.aliases, is_featured = excluded.is_featured;`,
  );
  for (const model of make.models) {
    lines.push(
      `insert into public.models (make_id, name, slug, aliases) select id, ${q(model.name)}, ${q(model.slug)}, ${arr(model.aliases)} from public.makes where slug = ${q(make.slug)} on conflict (make_id, slug) do nothing;`,
    );
  }
});

lines.push("", "-- Category groups");
[...CATEGORY_GROUPS, FALLBACK_CATEGORY_GROUP].forEach((g, i) => {
  lines.push(
    `insert into public.categories (name, slug, icon, description, sort_order) values (${q(g.name)}, ${q(g.slug)}, ${q(g.icon)}, ${q(g.description)}, ${i}) on conflict (slug) do nothing;`,
  );
});

lines.push("", "-- eBay leaf categories (all categories present in the export)");
const leaves = new Map<number, { name: string; group: string }>();
for (const p of products) leaves.set(p.category.ebayCategoryId, { name: p.category.name, group: p.category.groupSlug });
for (const [ebayId, leaf] of [...leaves].sort((a, b) => a[0] - b[0])) {
  lines.push(
    `insert into public.categories (name, slug, ebay_category_id, parent_id) select ${q(leaf.name)}, ${q(`${slugify(leaf.name, 60)}-${ebayId}`)}, ${ebayId}, id from public.categories where slug = ${q(leaf.group)} on conflict (ebay_category_id) do nothing;`,
  );
}

lines.push("", "-- DEMO donor vehicles (sample data for development; replace with real inventory)");
DEMO_VEHICLES.forEach((v, i) => {
  lines.push(
    `insert into public.donor_vehicles (stock_number, slug, year, make_id, model_id, trim, odometer, engine, transmission, drive_type, exterior_color, status, description, acquired_at)
  select ${q(v.stock)}, ${q(slugify(`${v.year} ${v.make} ${v.model} ${v.stock}`))}, ${v.year}, mk.id, mo.id, ${q(v.trim)}, ${v.odometer}, ${q(v.engine)}, ${q(v.transmission)}, ${q(v.drive)}, ${q(v.color)}, 'dismantling',
         'DEMO vehicle for development. Replace with a real donor vehicle.', date '2026-11-0${i + 1}'
    from public.makes mk join public.models mo on mo.make_id = mk.id and mo.slug = ${q(v.model)}
   where mk.slug = ${q(v.make)}
  on conflict (stock_number) do nothing;`,
  );
});

lines.push("", "-- Products (real listings from the eBay export)");
for (const p of picked) {
  const donor = DEMO_VEHICLES.find((v) => v.model === p.fitment.modelSlug && p.fitment.years.includes(v.year));
  lines.push(
    `insert into public.products (sku, slug, title, condition, status, price, currency, quantity, oem_part_number, interchange_numbers, placement, category_id, donor_vehicle_id, external_ids, source, listed_at)
values (${q(p.sku)}, ${q(p.slug)}, ${q(p.title)}, ${q(p.condition)}, ${q(p.status)}, ${p.price.toFixed(2)}, ${q(p.currency)}, ${p.quantity}, ${q(p.oemPartNumber)}, ${arr(p.interchangeNumbers)}, ${q(p.placement)},
        (select id from public.categories where ebay_category_id = ${p.category.ebayCategoryId}),
        ${donor ? `(select id from public.donor_vehicles where stock_number = ${q(donor.stock)})` : "null"},
        ${q(JSON.stringify(p.externalIds))}::jsonb, 'ebay', ${p.listedAt ? `${q(p.listedAt)}::timestamptz` : "null"})
on conflict (sku) do nothing;`,
  );
  const years = p.fitment.years.join(", ");
  lines.push(
    `insert into public.product_fitments (product_id, year, make_id, model_id, trim, engine)
  select pr.id, y, mk.id, mo.id, ${q(p.fitment.trim)}, ${q(p.fitment.engine)}
    from public.products pr, unnest(array[${years}]::smallint[]) y, public.makes mk
    left join public.models mo on mo.make_id = mk.id and mo.slug = ${q(p.fitment.modelSlug)}
   where pr.sku = ${q(p.sku)} and mk.slug = ${q(p.fitment.makeSlug)}
  on conflict do nothing;`,
  );
}

lines.push("", "commit;", "");
writeFileSync("supabase/seed.sql", lines.join("\n"));
console.log(`Wrote supabase/seed.sql with ${picked.length} products:`);
for (const p of picked) console.log(`  [${p.category.groupSlug}] ${p.title}`);
